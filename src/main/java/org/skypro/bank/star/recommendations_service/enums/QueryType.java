package org.skypro.bank.star.recommendations_service.enums;

/**
 * Типы запросов для динамических правил рекомендаций.
 * Определяет все поддерживаемые типы проверок, которые могут выполняться
 * для пользователя при оценке приемлемости для банковских продуктов.
 */
public enum QueryType {

    /**
     * Проверяет, является ли пользователь владельцем продукта указанного типа.
     * Пользователь считается владельцем, если у него есть хотя бы одна транзакция
     * по продуктам данного типа.
     * Аргументы: [ProductType]
     * Пример: ["DEBIT"] - проверяет наличие дебетовых продуктов
     */
    USER_OF,

    /**
     * Проверяет, является ли пользователь активным пользователем продукта указанного типа.
     * Активный пользователь - это пользователь с 5 или более транзакциями
     * по продуктам данного типа.
     * Аргументы: [ProductType]
     * Пример: ["DEBIT"] - проверяет активность по дебетовым продуктам
     */
    ACTIVE_USER_OF,

    /**
     * Сравнивает сумму транзакций указанного типа по продуктам указанного типа
     * с заданной константой с использованием оператора сравнения.
     * Аргументы: [ProductType, TransactionType, Operator, Amount]
     * Пример: ["DEBIT", "DEPOSIT", ">", "100000"] - сумма пополнений по дебету > 100,000
     */
    TRANSACTION_SUM_COMPARE,

    /**
     * Сравнивает сумму пополнений (DEPOSIT) с суммой трат (WITHDRAW)
     * по продуктам указанного типа с использованием оператора сравнения.
     * Аргументы: [ProductType, Operator]
     * Пример: ["DEBIT", ">"] - пополнения по дебету > трат по дебету
     */
    TRANSACTION_SUM_COMPARE_DEPOSIT_WITHDRAW
}
